fn emit_named_enum_helpers(out: &mut String, enums: &[NamedEnum]) {
    for item in enums {
        let c_name = named_c_type(&item.name);
        writeln!(
            out,
            "static int w_{}(ww_buf_t *b, {c_name} v) {{",
            item.name
        )
        .unwrap();
        writeln!(out, "    return w_u32(b, (uint32_t)v);").unwrap();
        writeln!(out, "}}").unwrap();
        writeln!(out).unwrap();

        writeln!(
            out,
            "static int rd_{}(ww_rd_t *r, {c_name} *out) {{",
            item.name
        )
        .unwrap();
        writeln!(out, "    uint32_t value;").unwrap();
        writeln!(out, "    int rc = rd_u32(r, &value);").unwrap();
        writeln!(out, "    if (rc) return rc;").unwrap();
        if item.open {
            writeln!(out, "    *out = value; return WW_OK;\n}}\n").unwrap();
            continue;
        }
        writeln!(out, "    switch (value) {{").unwrap();
        for entry in &item.entries {
            writeln!(
                out,
                "    case {}: *out = WAYWALLEN_{}_{}; return WW_OK;",
                entry.value,
                item.name.to_uppercase(),
                entry.name.to_uppercase()
            )
            .unwrap();
        }
        writeln!(out, "    default: return WW_ERR_BAD_ENUM;").unwrap();
        writeln!(out, "    }}").unwrap();
        writeln!(out, "}}").unwrap();
        writeln!(out).unwrap();
    }
}

fn emit_named_helpers(out: &mut String, structs: &[NamedStruct]) {
    for item in structs {
        let c_name = named_c_type(&item.name);
        writeln!(
            out,
            "static int w_{}(ww_buf_t *b, const {c_name} *v) {{",
            item.name
        )
        .unwrap();
        writeln!(out, "    int rc;").unwrap();
        if item.tagged {
            crate::tagged::c_encode(out, &item.fields, "v", "b");
        } else {
            for field in &item.fields {
                let name = c_field_name(&field.name);
                let call = encode_call_for(&field.ty, &name);
                let arg = match field.ty {
                    ArgType::Bool
                    | ArgType::U32
                    | ArgType::I32
                    | ArgType::U64
                    | ArgType::I64
                    | ArgType::F32
                    | ArgType::F64
                    | ArgType::Enum(_) => format!("v->{name}"),
                    ArgType::String => format!("v->{name}"),
                    ArgType::Rect | ArgType::KvList | ArgType::Array(_) | ArgType::Named(_) => {
                        format!("&v->{name}")
                    }
                };
                writeln!(out, "    if ((rc = {call}(b, {arg}))) return rc;").unwrap();
            }
        }
        writeln!(out, "    return WW_OK;").unwrap();
        writeln!(out, "}}").unwrap();
        writeln!(out).unwrap();

        writeln!(
            out,
            "static int rd_{}(ww_rd_t *r, {c_name} *v) {{",
            item.name
        )
        .unwrap();
        writeln!(out, "    int rc;").unwrap();
        if item.tagged {
            crate::tagged::c_decode(out, &item.fields, "v", "r");
        } else {
            for field in &item.fields {
                let name = c_field_name(&field.name);
                let call = decode_call_for(&field.ty);
                writeln!(out, "    if ((rc = {call}(r, &v->{name}))) return rc;").unwrap();
            }
        }
        writeln!(out, "    return WW_OK;").unwrap();
        writeln!(out, "}}").unwrap();
        writeln!(out).unwrap();

        writeln!(out, "static void free_{}({c_name} *v) {{", item.name).unwrap();
        let owned: Vec<_> = item
            .fields
            .iter()
            .filter(|field| ty_owns_heap(&field.ty))
            .collect();
        if owned.is_empty() {
            writeln!(out, "    (void)v;").unwrap();
        } else {
            for field in owned {
                let name = c_field_name(&field.name);
                writeln!(out, "    {}", free_stmt_for_base(&field.ty, "v", &name)).unwrap();
            }
        }
        writeln!(out, "}}").unwrap();
        writeln!(out).unwrap();

        writeln!(out, "void waywallen_{}_free({c_name} *value) {{", item.name).unwrap();
        writeln!(out, "    if (!value) return;").unwrap();
        writeln!(out, "    free_{}(value);", item.name).unwrap();
        writeln!(out, "    memset(value, 0, sizeof(*value));").unwrap();
        writeln!(out, "}}").unwrap();
        writeln!(out).unwrap();
    }
}

fn emit_message_impl(out: &mut String, m: &Message, kind: MsgKind) {
    let type_name = message_type_name(m, kind);
    let fn_prefix = type_name.trim_end_matches("_t").to_string();
    if m.tagged {
        writeln!(out, "static int {fn_prefix}_read(ww_rd_t *reader, {type_name} *value) {{\n    int rc;\n    (void)value;").unwrap();
        crate::tagged::c_decode(out, &m.args, "value", "reader");
        writeln!(out, "    return WW_OK;\n}}\n").unwrap();
    }

    // ---- encode ----
    writeln!(
        out,
        "int {fn_prefix}_encode(const {type_name} *m, ww_buf_t *out) {{"
    )
    .unwrap();
    if m.args.is_empty() && !m.tagged {
        writeln!(out, "    (void)m; (void)out;").unwrap();
        writeln!(out, "    return WW_OK;").unwrap();
    } else {
        writeln!(out, "    int rc;").unwrap();
        writeln!(out, "    (void)m;").unwrap();
        if m.tagged {
            crate::tagged::c_encode(out, &m.args, "m", "out");
        } else {
            for a in &m.args {
                let field = c_field_name(&a.name);
                let call = encode_call_for(&a.ty, &field);
                writeln!(
                    out,
                    "    if ((rc = {call}(out, {arg}))) return rc;",
                    arg = encode_arg_expr(&a.ty, &field)
                )
                .unwrap();
            }
        }
        writeln!(out, "    return WW_OK;").unwrap();
    }
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();

    // ---- decode ----
    writeln!(
        out,
        "int {fn_prefix}_decode(const uint8_t *buf, size_t len, {type_name} *out) {{"
    )
    .unwrap();
    writeln!(out, "    memset(out, 0, sizeof(*out));").unwrap();
    writeln!(out, "    ww_rd_t r = {{ buf, 0, len }};").unwrap();
    if m.args.is_empty() && !m.tagged {
        writeln!(out, "    (void)r;").unwrap();
    } else {
        writeln!(out, "    int rc;").unwrap();
        if m.tagged {
            writeln!(out, "    if ((rc = {fn_prefix}_read(&r, out))) goto fail;").unwrap();
        } else {
            for a in &m.args {
                let field = c_field_name(&a.name);
                let call = decode_call_for(&a.ty);
                writeln!(out, "    if ((rc = {call}(&r, &out->{field}))) goto fail;").unwrap();
            }
        }
    }
    writeln!(out, "    if (r.pos != r.len) {{").unwrap();
    if !m.args.is_empty() || m.tagged {
        writeln!(out, "        int rc2 = WW_ERR_TRAILING;").unwrap();
        writeln!(out, "        (void)rc2;").unwrap();
        writeln!(out, "        {fn_prefix}_free(out);").unwrap();
    } else {
        writeln!(
            out,
            "        /* empty message; no allocations to release */"
        )
        .unwrap();
    }
    writeln!(out, "        return WW_ERR_TRAILING;").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out, "    return WW_OK;").unwrap();
    if !m.args.is_empty() || m.tagged {
        writeln!(out, "fail:").unwrap();
        writeln!(out, "    {fn_prefix}_free(out);").unwrap();
        writeln!(out, "    return rc;").unwrap();
    }
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();

    // ---- free ----
    writeln!(out, "void {fn_prefix}_free({type_name} *m) {{").unwrap();
    let owned: Vec<_> = m.args.iter().filter(|a| ty_owns_heap(&a.ty)).collect();
    if owned.is_empty() {
        writeln!(out, "    (void)m;").unwrap();
    } else {
        for a in &owned {
            let field = c_field_name(&a.name);
            writeln!(out, "    {}", free_stmt_for(&a.ty, &field)).unwrap();
        }
    }
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();

    // ---- expected_fds ----
    writeln!(
        out,
        "uint32_t {fn_prefix}_expected_fds(const {type_name} *m) {{"
    )
    .unwrap();
    match &m.fds {
        FdSpec::None => {
            writeln!(out, "    (void)m;").unwrap();
            writeln!(out, "    return 0;").unwrap();
        }
        FdSpec::Fixed(n) => {
            writeln!(out, "    (void)m;").unwrap();
            writeln!(out, "    return {n};").unwrap();
        }
        FdSpec::Product(fields) => {
            let expr = fields
                .iter()
                .map(|path| {
                    let field_path = path
                        .split('.')
                        .map(c_field_name)
                        .collect::<Vec<_>>()
                        .join(".");
                    format!("(uint64_t)m->{field_path}")
                })
                .collect::<Vec<_>>()
                .join(" * ");
            writeln!(out, "    return (uint32_t)({expr});").unwrap();
        }
    }
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();
}

pub(crate) fn encode_call_for(ty: &ArgType, _field: &str) -> String {
    match ty {
        ArgType::Bool => "w_bool".into(),
        ArgType::U32 => "w_u32".into(),
        ArgType::I32 => "w_i32".into(),
        ArgType::U64 => "w_u64".into(),
        ArgType::I64 => "w_i64".into(),
        ArgType::F32 => "w_f32".into(),
        ArgType::F64 => "w_f64".into(),
        ArgType::String => "w_string".into(),
        ArgType::Rect => "w_rect".into(),
        ArgType::KvList => "w_kv_list".into(),
        ArgType::Array(elem) => match **elem {
            ArgType::U32 => "w_array_u32".into(),
            ArgType::I32 => "w_array_i32".into(),
            ArgType::U64 => "w_array_u64".into(),
            ArgType::I64 => "w_array_i64".into(),
            ArgType::F32 => "w_array_f32".into(),
            ArgType::F64 => "w_array_f64".into(),
            ArgType::String => "w_array_string".into(),
            _ => panic!("bad array"),
        },
        ArgType::Named(name) => format!("w_{name}"),
        ArgType::Enum(name) => format!("w_{name}"),
    }
}

fn encode_arg_expr(ty: &ArgType, field: &str) -> String {
    match ty {
        ArgType::Bool
        | ArgType::U32
        | ArgType::I32
        | ArgType::U64
        | ArgType::I64
        | ArgType::F32
        | ArgType::F64
        | ArgType::Enum(_) => {
            format!("m->{field}")
        }
        ArgType::String => format!("m->{field}"),
        ArgType::Rect | ArgType::KvList | ArgType::Array(_) | ArgType::Named(_) => {
            format!("&m->{field}")
        }
    }
}

pub(crate) fn decode_call_for(ty: &ArgType) -> String {
    match ty {
        ArgType::Bool => "rd_bool".into(),
        ArgType::U32 => "rd_u32".into(),
        ArgType::I32 => "rd_i32".into(),
        ArgType::U64 => "rd_u64".into(),
        ArgType::I64 => "rd_i64".into(),
        ArgType::F32 => "rd_f32".into(),
        ArgType::F64 => "rd_f64".into(),
        ArgType::String => "rd_string".into(),
        ArgType::Rect => "rd_rect".into(),
        ArgType::KvList => "rd_kv_list".into(),
        ArgType::Array(elem) => match **elem {
            ArgType::U32 => "rd_array_u32".into(),
            ArgType::I32 => "rd_array_i32".into(),
            ArgType::U64 => "rd_array_u64".into(),
            ArgType::I64 => "rd_array_i64".into(),
            ArgType::F32 => "rd_array_f32".into(),
            ArgType::F64 => "rd_array_f64".into(),
            ArgType::String => "rd_array_string".into(),
            _ => panic!("bad array"),
        },
        ArgType::Named(name) => format!("rd_{name}"),
        ArgType::Enum(name) => format!("rd_{name}"),
    }
}

fn ty_owns_heap(ty: &ArgType) -> bool {
    matches!(
        ty,
        ArgType::String | ArgType::KvList | ArgType::Array(_) | ArgType::Named(_)
    )
}

fn free_stmt_for(ty: &ArgType, field: &str) -> String {
    free_stmt_for_base(ty, "m", field)
}

fn free_stmt_for_base(ty: &ArgType, base: &str, field: &str) -> String {
    match ty {
        ArgType::String => format!("free({base}->{field}); {base}->{field} = NULL;"),
        ArgType::KvList => format!("free_kv_list(&{base}->{field});"),
        ArgType::Array(elem) => match **elem {
            ArgType::String => format!("free_array_string(&{base}->{field});"),
            _ => format!(
                "free({base}->{field}.data); {base}->{field}.data = NULL; {base}->{field}.count = 0;"
            ),
        },
        ArgType::Named(name) => format!("free_{name}(&{base}->{field});"),
        _ => format!("/* {field}: no heap */"),
    }
}

