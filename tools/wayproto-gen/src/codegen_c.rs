#[derive(Copy, Clone, PartialEq, Eq)]
enum MsgKind {
    Request,
    EventIn,
    Event,
}

impl MsgKind {
    fn inbound_for(k: InboundKind) -> Self {
        match k {
            InboundKind::Request => Self::Request,
            InboundKind::EventIn => Self::EventIn,
        }
    }
    fn prefix(self) -> &'static str {
        match self {
            Self::Request => "ww_req_",
            Self::EventIn => "ww_evt_in_",
            Self::Event => "ww_evt_",
        }
    }
    fn enum_prefix(self) -> &'static str {
        match self {
            Self::Request => "WW_REQ_",
            Self::EventIn => "WW_EVT_IN_",
            Self::Event => "WW_EVT_",
        }
    }
    fn enum_typedef(self) -> (&'static str, &'static str) {
        match self {
            Self::Request => ("ww_request_op", "ww_request_op_t"),
            Self::EventIn => ("ww_event_in_op", "ww_event_in_op_t"),
            Self::Event => ("ww_event_op", "ww_event_op_t"),
        }
    }
}

fn emit_header_prologue(out: &mut String, p: &Protocol) {
    writeln!(
        out,
        "/* AUTO-GENERATED by wayproto-gen. DO NOT EDIT BY HAND. */"
    )
    .unwrap();
    writeln!(out, "/* clang-format off */").unwrap();
    writeln!(out, "/* Source: protocol/{}_v{}.xml */", p.name, p.version).unwrap();
    writeln!(out).unwrap();
    writeln!(out, "#ifndef WAYWALLEN_PROTO_H").unwrap();
    writeln!(out, "#define WAYWALLEN_PROTO_H").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "#include <stdint.h>").unwrap();
    writeln!(out, "#include <stddef.h>").unwrap();
    writeln!(out, "#include <stdbool.h>").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "#ifdef __cplusplus").unwrap();
    writeln!(out, "extern \"C\" {{").unwrap();
    writeln!(out, "#endif").unwrap();
    writeln!(out).unwrap();
    writeln!(
        out,
        "#define WW_PROTOCOL_NAME    \"{}-v{}\"",
        p.name.replace('_', "-"),
        p.version
    )
    .unwrap();
    writeln!(out, "#define WW_PROTOCOL_VERSION {}", p.version).unwrap();
    writeln!(out).unwrap();
}

fn emit_header_epilogue(out: &mut String) {
    writeln!(out).unwrap();
    writeln!(out, "#ifdef __cplusplus").unwrap();
    writeln!(out, "}} /* extern \"C\" */").unwrap();
    writeln!(out, "#endif").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "#endif /* WAYWALLEN_PROTO_H */").unwrap();
}

fn emit_common_types(out: &mut String) {
    emit_value_types(out);
    out.push_str(
        r#"/* --- Codec buffer + return codes --- */

typedef struct ww_buf {
    uint8_t *data;
    size_t len;
    size_t cap;
} ww_buf_t;

/* Return codes: 0 = success, negative = -errno-ish. */
#define WW_OK                  0
#define WW_ERR_SHORT           (-1)   /* buffer truncated */
#define WW_ERR_BAD_STRING      (-2)   /* malformed length-prefixed string */
#define WW_ERR_BAD_ARRAY       (-3)   /* array length overflow */
#define WW_ERR_TRAILING        (-4)   /* unexpected trailing bytes */
#define WW_ERR_UNKNOWN_OPCODE  (-5)
#define WW_ERR_NOMEM           (-6)
#define WW_ERR_OVERFLOW        (-7)   /* frame bigger than u16 can address */
#define WW_ERR_BAD_BOOL        (-8)   /* boolean is not canonical 0/1 */
#define WW_ERR_BAD_ENUM        (-9)   /* enum value is not declared */

"#,
    );
}

