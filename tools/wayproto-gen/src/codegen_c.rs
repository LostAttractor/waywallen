fn emit_named_types(out: &mut String, enums: &[NamedEnum], structs: &[NamedStruct]) {
    if enums.is_empty() && structs.is_empty() {
        return;
    }
    writeln!(out, "#ifndef WAYWALLEN_PROTOCOL_NAMED_TYPES_DEFINED").unwrap();
    writeln!(out, "#define WAYWALLEN_PROTOCOL_NAMED_TYPES_DEFINED").unwrap();
    writeln!(out).unwrap();
    for item in enums {
        let type_name = named_c_type(&item.name);
        if item.open {
            writeln!(out, "typedef uint32_t {type_name};").unwrap();
            for entry in &item.entries {
                writeln!(
                    out,
                    "#define WAYWALLEN_{}_{} UINT32_C({})",
                    item.name.to_uppercase(),
                    entry.name.to_uppercase(),
                    entry.value
                )
                .unwrap();
            }
            continue;
        }
        writeln!(out, "typedef enum {} {{", type_name.trim_end_matches("_t")).unwrap();
        for entry in &item.entries {
            writeln!(
                out,
                "    WAYWALLEN_{}_{} = {},",
                item.name.to_uppercase(),
                entry.name.to_uppercase(),
                entry.value
            )
            .unwrap();
        }
        writeln!(out, "}} {type_name};").unwrap();
        writeln!(out).unwrap();
    }
    for item in structs {
        let type_name = named_c_type(&item.name);
        writeln!(
            out,
            "typedef struct {} {{",
            type_name.trim_end_matches("_t")
        )
        .unwrap();
        for field in &item.fields {
            if field.optional {
                writeln!(out, "    bool has_{};", c_field_name(&field.name)).unwrap();
            }
            writeln!(
                out,
                "    {} {};",
                c_type(&field.ty),
                c_field_name(&field.name)
            )
            .unwrap();
        }
        writeln!(out, "}} {type_name};").unwrap();
        writeln!(out).unwrap();
    }
    writeln!(out, "#endif /* WAYWALLEN_PROTOCOL_NAMED_TYPES_DEFINED */").unwrap();
    writeln!(out).unwrap();
}

fn emit_opcodes(out: &mut String, p: &Protocol, inbound: MsgKind) {
    writeln!(out, "/* --- Opcodes --- */").unwrap();
    writeln!(out).unwrap();
    let (in_tag, in_typedef) = inbound.enum_typedef();
    writeln!(out, "typedef enum {in_tag} {{").unwrap();
    for m in &p.requests {
        writeln!(
            out,
            "    {}{} = {},",
            inbound.enum_prefix(),
            m.name.to_uppercase(),
            m.opcode
        )
        .unwrap();
    }
    writeln!(out, "}} {in_typedef};").unwrap();
    writeln!(out).unwrap();
    let (out_tag, out_typedef) = MsgKind::Event.enum_typedef();
    writeln!(out, "typedef enum {out_tag} {{").unwrap();
    for m in &p.events {
        writeln!(
            out,
            "    {}{} = {},",
            MsgKind::Event.enum_prefix(),
            m.name.to_uppercase(),
            m.opcode
        )
        .unwrap();
    }
    writeln!(out, "}} {out_typedef};").unwrap();
    writeln!(out).unwrap();
}

fn emit_message_struct(out: &mut String, m: &Message, kind: MsgKind) {
    let type_name = message_type_name(m, kind);
    writeln!(out, "typedef struct {} {{", type_name).unwrap();
    if m.args.is_empty() {
        writeln!(out, "    int _empty; /* C forbids empty structs */").unwrap();
    } else {
        for a in &m.args {
            if a.optional {
                writeln!(out, "    bool has_{};", c_field_name(&a.name)).unwrap();
            }
            let ty = c_type(&a.ty);
            let field = c_field_name(&a.name);
            // Pointer types render `char *name;` (star glued to name);
            // everything else renders `uint32_t name;`.
            if ty.ends_with('*') {
                writeln!(out, "    {ty}{field};").unwrap();
            } else {
                writeln!(out, "    {ty} {field};").unwrap();
            }
        }
    }
    writeln!(out, "}} {};", type_name).unwrap();
    writeln!(out).unwrap();
}

fn emit_function_decls(out: &mut String, p: &Protocol, inbound: MsgKind) {
    writeln!(out, "/* --- Per-message functions ---").unwrap();
    writeln!(
        out,
        " * encode:        append wire body to `out` (header is the caller's job)"
    )
    .unwrap();
    writeln!(
        out,
        " * decode:        consume `len` bytes; on success owns heap allocations"
    )
    .unwrap();
    writeln!(
        out,
        " * free:          release any heap fields the decoder populated"
    )
    .unwrap();
    writeln!(
        out,
        " * expected_fds:  how many SCM_RIGHTS fds the wire frame must carry"
    )
    .unwrap();
    writeln!(out, " */").unwrap();
    writeln!(out).unwrap();

    for m in &p.requests {
        emit_message_decls(out, m, inbound);
    }
    for m in &p.events {
        emit_message_decls(out, m, MsgKind::Event);
    }

    // ww_buf helpers.
    writeln!(out, "/* --- Output buffer helpers --- */").unwrap();
    writeln!(out, "void ww_buf_init(ww_buf_t *b);").unwrap();
    writeln!(out, "void ww_buf_free(ww_buf_t *b);").unwrap();
    writeln!(out, "int  ww_buf_reserve(ww_buf_t *b, size_t additional);").unwrap();
    writeln!(out).unwrap();
}

fn emit_message_decls(out: &mut String, m: &Message, kind: MsgKind) {
    let type_name = message_type_name(m, kind);
    let fn_prefix = type_name.trim_end_matches("_t");
    writeln!(
        out,
        "int  {fn_prefix}_encode(const {type_name} *m, ww_buf_t *out);"
    )
    .unwrap();
    writeln!(
        out,
        "int  {fn_prefix}_decode(const uint8_t *buf, size_t len, {type_name} *out);"
    )
    .unwrap();
    writeln!(out, "void {fn_prefix}_free({type_name} *m);").unwrap();
    let fd_signature = match &m.fds {
        FdSpec::None | FdSpec::Fixed(_) => {
            format!("uint32_t {fn_prefix}_expected_fds(const {type_name} *m);")
        }
        FdSpec::Product(_) => {
            format!("uint32_t {fn_prefix}_expected_fds(const {type_name} *m);")
        }
    };
    writeln!(out, "{fd_signature}").unwrap();
    writeln!(out).unwrap();
}

